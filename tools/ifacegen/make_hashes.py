#!/usr/bin/env python3
"""Write tests/TestHashGolden.HC: the Jazzy RIHS01 type hash of every
message in interfaces/Index.txt, computed by an independent
implementation (rosbags' Typestore.hash_rihs01).

One change: rosidl turns .msg `char` into IDL uint8 (rosidl_adapter's
MSG_TYPE_TO_IDL), so its type id is 3, not 13 as rosbags has it.

  /tmp/v/bin/python tools/ifacegen/make_hashes.py
"""

import os
import sys

import rosbags.typesys.store as store

sys.path.insert(0, os.path.dirname(__file__))
from make_golden import ROOT, load_typestore  # noqa: E402

store.TIDMAP["char"] = store.TIDMAP["uint8"]


def main():
    ts, names = load_typestore()
    lines = ["//Generated by tools/ifacegen/make_hashes.py. Don't edit.",
             "//Jazzy type hashes from an independent implementation (rosbags).", "",
             "U0 TestHashGolden()", "{", "  RosTestGroup(\"Golden type hashes\");"]
    n = 0
    for name, rb_name in names:
        if "/srv/" in name:
            continue
        lines.append('  RosTestStr("%s",RosTypeHash(RosTypeFind("%s")),\n\t"%s");'
                     % (name, name, ts.hash_rihs01(rb_name)))
        n += 1
    lines.append("}")
    with open(os.path.join(ROOT, "tests", "TestHashGolden.HC"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("TestHashGolden.HC: %d messages" % n)


if __name__ == "__main__":
    main()
